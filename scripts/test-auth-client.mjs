import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const code=readFileSync(new URL('../auth-client.js',import.meta.url),'utf8');
const requests=[];
const window={APP_CONFIG:{AUTH_URL:'https://auth.example.test'}};
const fetch=async(url,options)=>{
 requests.push({url,options});
 if(url.endsWith('/login'))return options.body.includes('bad@example.test') ? new Response(JSON.stringify({error:'Fel e-postadress eller lösenord'}),{status:401}) : new Response(JSON.stringify({token:'test-session-token'}));
 if(url.endsWith('/me'))return new Response(JSON.stringify({memberships:[{team_id:'NSK Team 18',role:'team_admin'}],permissions:['roster:manage']}));
 return new Response(JSON.stringify({ok:true}));
};
vm.runInNewContext(code,{window,fetch,Headers,Error,JSON});
const auth=window.NSK_AUTH;
assert.equal(auth.me(),null);
assert.throws(()=>auth.authRequest('/api/auth/me'),/Inte inloggad/);
await auth.login('test@example.test','test-password');
assert.equal(auth.teamAccess('NSK Team 18','roster:manage'),true);
assert.equal(auth.teamAccess('Annat lag','roster:manage'),false);
const identity=auth.me();
identity.memberships[0].role='viewer';
assert.equal(auth.teamAccess('NSK Team 18','roster:manage'),false,'Viewer cannot manage even with global permission');
identity.memberships[0].role='team_admin';
await assert.rejects(()=>auth.authRequest('/api/lag'),/Endast autentiserings-API/);
assert(requests.every(r=>r.url.startsWith('https://auth.example.test/api/auth/')));
assert(requests.some(r=>r.url.endsWith('/me')&&r.options.headers.get('Authorization')==='Bearer test-session-token'));
await auth.logout();
assert.equal(auth.me(),null);
assert.throws(()=>auth.authRequest('/api/auth/me'),/Inte inloggad/);

const previousCount=requests.length;
await assert.rejects(()=>auth.login('bad@example.test','wrong-password'),/Fel e-postadress eller lösenord/);
assert.equal(auth.me(),null,'Failed login must clear prior identity');
assert.equal(requests.length,previousCount+1,'Failed login must not fetch identity');
assert.throws(()=>auth.authRequest('/api/auth/me'),/Inte inloggad/);
console.log('PASS login, membership, endpoint isolation, logout and failed login');
